#!/usr/bin/env python3
"""Embed the Text feature's character maps in patches/text/FontMaps.cs.

The fonts the port ships with are files a player can edit: NAME.png (every letter),
NAME.json (where each letter sits), NAME_template.png (the same grid, empty) and
NAME_spacing.json, for the dialogue, sign and menu fonts. The game writes them into
its data directory's fonts/ folder the first time it needs them and reads them back
from there, so an edit there changes the game. To change the fonts the port ships,
edit them there (or anywhere), then run this to put them into the source:

    python3 scripts/text_fonts.py fonts/

Standard library only. Each file goes in as base64 under its file name; JSON is
checked to parse first, since the game reads a broken file as missing.
"""
import base64
import json
import pathlib
import sys

FONTS = ("dialogue", "sign", "menu")
SUFFIXES = (".png", ".json", "_template.png", "_spacing.json")
OUT = pathlib.Path(__file__).resolve().parent.parent / "patches" / "text" / "FontMaps.cs"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    src = pathlib.Path(sys.argv[1])
    entries = []
    for font in FONTS:
        for suffix in SUFFIXES:
            path = src / (font + suffix)
            if not path.is_file():
                print(f"missing {path}", file=sys.stderr)
                return 1
            data = path.read_bytes()
            if suffix.endswith(".json"):
                try:
                    json.loads(data)
                except ValueError as e:
                    print(f"{path}: not valid JSON: {e}", file=sys.stderr)
                    return 1
            entries.append((path.name, base64.b64encode(data).decode("ascii")))

    lines = [
        "// Generated by scripts/text_fonts.py from the character maps; do not edit by hand.",
        "// The fonts the port ships: written into the data directory's fonts/ folder when",
        "// it has none, and read from there. See \"The game's text in new fonts\" in",
        "// docs/PATCHES_AND_MODS.md.",
        "namespace Kf2.Text;",
        "",
        "static class FontMaps",
        "{",
        "    /// <summary>Each shipped file, by its name in the fonts folder, as base64.</summary>",
        "    public static readonly IReadOnlyDictionary<string, string> Files = new Dictionary<string, string>",
        "    {",
    ]
    for name, b64 in entries:
        lines.append(f'        ["{name}"] =')
        for i in range(0, len(b64), 96):
            tail = " +" if i + 96 < len(b64) else ","
            lines.append(f'            "{b64[i:i + 96]}"{tail}')
    lines += ["    };", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(entries)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
